// ============================================================
//  Buzzer.h — активний п'єзо-бузер (FR-4). Веде себе як просте
//  апаратне джерело сигналу: alarmOn()/alarmOff() кажуть, чи має
//  зараз лунати сигнал, а update() (кличеться щоцикл) сама
//  вмикає/вимикає пищалку з рівним інтервалом ("біп-пауза-біп"),
//  бо активний бузер має власний генератор і реагує лише на
//  HIGH/LOW, а не на частоту. Нічого не знає про канали чи
//  acknowledge — це турбота ChannelTemp/main.cpp.
// ============================================================
#pragma once

#include <Arduino.h>
#include "Timer.h"

class Buzzer {
private:
    uint8_t pin;
    Timer beep_timer;
    bool active;
    bool sounding;   // чи пищалка зараз фізично гуде (в межах фази "біп")

public:
    explicit Buzzer(uint8_t pin_);

    void alarmOn();    // почати сигнал; якщо вже увімкнено — нічого не робить
    void alarmOff();   // зупинити сигнал
    void update();      // викликати щоцикл — перемикає біп/пауза з рівним інтервалом
};
